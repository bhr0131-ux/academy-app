/* 앱이 그림을 갖고 있는가 (없으면 운영체제 이모지로 그린다) */
const OWNED = new Set(REWARD_EMOJI.map(emojiFileName));
export const hasEmojiArt = (emoji) => OWNED.has(emojiFileName(emoji));
