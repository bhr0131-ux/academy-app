/* 유니코드 → 파일 이름. ZWJ(200D)가 없으면 VS16(FE0F)은 뺀다 (Twemoji 규칙).
   예) 🍪 → 1f36a   ✈️ → 2708 */
export const emojiFileName = (emoji) => {
  const cps = [...String(emoji || "")].map(c => c.codePointAt(0));
  if (!cps.length) return "";
  const keep = cps.includes(0x200D) ? cps : cps.filter(c => c !== 0xFE0F);
  return keep.map(c => c.toString(16)).join("-");
};

/* 고르기 격자에 나오는 순서 — 앞쪽 22개는 기본 보상 세트가 실제로 쓰는 것들이고,
   뒤쪽 22개는 아이 보상으로 자주 나올 만한 것들을 덧붙였다. */
